import request from 'supertest'
import { randomUUID } from 'node:crypto'
import { app } from '../helpers/testServer.js'
import { registerUser } from '../helpers/authHelper.js'
import { createChat } from '../helpers/chatHelper.js'
import { sendMessage } from '../helpers/messageHelper.js'
import { prisma, resetDatabase, disconnectPrisma } from '../helpers/prismaTestClient.js'

beforeEach(async () => {
  await resetDatabase()
})

afterAll(async () => {
  await resetDatabase()
  await disconnectPrisma()
})

describe('GET /chats/:chatId/messages', () => {
  it('rejects requests with no auth token with 401', async () => {
    const dragon = await registerUser()
    const lucky = await registerUser()
    const chat = await createChat({ token: dragon.token, memberIds: [lucky.userId] })
    const res = await request(app).get(`/chats/${chat.id}/messages`)
    expect(res.status).toBe(401)
  })
  it('rejects a user who is not a member of the chat with 403', async () => {
    const dragon = await registerUser()
    const lucky = await registerUser()
    const jasmine = await registerUser()
    const chat = await createChat({ token: dragon.token, memberIds: [lucky.userId] })
    const res = await request(app)
      .get(`/chats/${chat.id}/messages`)
      .set('Authorization', `Bearer ${jasmine.token}`)
    expect(res.status).toBe(403)
    expect(res.body.success).toBe(false)
    expect(res.body.message).toBe('Not a member of this chat.')
  })
  it('rejects a malformed chatId with 400', async () => {
    const dragon = await registerUser()
    const res = await request(app)
      .get(`/chats/not-a-valid-uuid/messages`)
      .set('Authorization', `Bearer ${dragon.token}`)
    expect(res.status).toBe(400)
  })
  it('returns an empty message list for a chat with no messages yet', async () => {
    const dragon = await registerUser()
    const lucky = await registerUser()
    const chat = await createChat({ token: dragon.token, memberIds: [lucky.userId] })
    const res = await request(app)
      .get(`/chats/${chat.id}/messages`)
      .set('Authorization', `Bearer ${dragon.token}`)
    expect(res.status).toBe(200)
    expect(res.body.chat.messages).toEqual([])
    expect(res.body.hasMore).toBe(false)
  })
  it('returns messages for a plain member, not just the admin', async () => {
    const dragon = await registerUser()
    const lucky = await registerUser()
    const chat = await createChat({ token: dragon.token, memberIds: [lucky.userId] })
    await sendMessage({ token: dragon.token, chatId: chat.id, text: 'Hello Lucky!'})
    const res = await request(app)
      .get(`/chats/${chat.id}/messages`)
      .set('Authorization', `Bearer ${lucky.token}`)
    expect(res.status).toBe(200)
    expect(res.body.chat.messages).toHaveLength(1)
    expect(res.body.chat.messages[0]).toMatchObject({ text: 'Hello Lucky!' })
  })
})

